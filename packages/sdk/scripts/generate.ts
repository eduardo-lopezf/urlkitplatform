/**
 * Generates the SDK types from the published contract (004/T003, research R1, Principio IX):
 *
 *   pnpm --filter @urlkit/sdk generate
 *
 * Run it after every change to packages/contracts/openapi.json. tests/contract.test.ts fails while
 * src/generated/openapi.ts is out of date.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const CONTRACT = new URL('../../contracts/openapi.json', import.meta.url);
const OUTPUT = new URL('../src/generated/openapi.ts', import.meta.url);

interface Contract {
  info: { version: string };
  servers?: Array<{ url: string }>;
  paths: Record<
    string,
    Record<
      string,
      { operationId?: string; tags?: string[]; parameters?: Array<{ in: string; name: string }> }
    >
  >;
}

/** `operationId` → path and whether it takes `?lang`, for every `tools` operation. */
function toolOperations(contract: Contract): Record<string, { path: string; lang: boolean }> {
  const out: Record<string, { path: string; lang: boolean }> = {};
  for (const [path, methods] of Object.entries(contract.paths))
    for (const op of Object.values(methods))
      if (op.operationId && op.tags?.includes('tools'))
        out[op.operationId] = {
          path,
          lang: (op.parameters ?? []).some((p) => p.in === 'query' && p.name === 'lang'),
        };
  return out;
}

/** The whole generated module, so the contract test can compare it in memory. */
export async function generate(contractText: string): Promise<string> {
  const contract = JSON.parse(contractText) as Contract;
  const types = astToString(await openapiTS(JSON.parse(contractText)));
  return [
    '// GENERATED by scripts/generate.ts from packages/contracts/openapi.json. Do not edit:',
    '// run `pnpm --filter @urlkit/sdk generate` after changing the contract.',
    '',
    `/** Version of the /v1 contract this SDK was generated from. */`,
    `export const CONTRACT_VERSION = ${JSON.stringify(contract.info.version)};`,
    `/** Production base URL declared by the contract. */`,
    `export const DEFAULT_BASE_URL = ${JSON.stringify(contract.servers?.[0]?.url ?? '')};`,
    `/** Every tool operation of the contract: path and whether it accepts \`?lang\`. */`,
    `export const TOOL_OPERATIONS = ${JSON.stringify(toolOperations(contract), null, 2)} as const;`,
    '',
    types,
  ].join('\n');
}

export function readContract(): string {
  return readFileSync(CONTRACT, 'utf8');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(OUTPUT, await generate(readContract()));
  process.stdout.write('sdk: src/generated/openapi.ts generated\n');
}
